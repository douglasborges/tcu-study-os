export function migrateTiRamon(current){
 if(!current||!Array.isArray(current.subjects))return current;
 const ti=current.subjects.find(s=>s.id==='ti');
 if(!ti||!Array.isArray(ti.units))return current;
 const normalizeCode=t=>String(t||'').match(/^(FD\d+|SI\d+|TI\d+(?:\.II)?(?:\.I)?(?:-B)?|INF\d+)/i)?.[1]?.toUpperCase()||'';
 const coreSet=new Set(TI_RAMON_ORIGINAL);
 const codes=new Set(ti.units.map(x=>normalizeCode(x.title)).filter(Boolean));
 const oldCourse=ti.course;
 if(oldCourse!==COURSE){
   if(!ti.previousCourse)ti.previousCourse=oldCourse;
   ti.course=COURSE;
 }
 ti.catalogPending=false;
 ti.catalogSource={provider:'TI Total',teacher:'Ramon Souza',catalog:'TI TOTAL.pdf',catalogDate:'2026-11-02',scope:'TCU Geral / edital 2021 + recortes Cebraspe 2023-2026'};
 ti.examReference={label:'TCU Geral — planejamento Cebraspe (edital futuro não publicado)',reference:'TCU/FGV 2021 + editais Cebraspe TCU 2025, fiscal e controle 2023-2026'};
 for(const u of ti.units){
   if(/^FELIPE-TID-/.test(String(u.id))||String(u.courseId||'').startsWith('felipe-')){u.hiddenFromRoute=true;continue;}
   const code=normalizeCode(u.title);
   if(coreSet.has(code)){
     u.hiddenFromRoute=false;
     u.courseId=COURSE_ID;
   }
 }
 for(const m of TI_RAMON_EXTRA){
   if(codes.has(m.code))continue;
   ti.units.push({
     id:'ti-ramon-'+m.code.toLowerCase().replace(/[^a-z0-9]+/g,'-'),
     title:m.code+' - '+m.title,
     order:ti.units.length+1,
     theoryDone:false,theoryDate:'',batteryDone:false,generalDone:false,materialReady:false,
     battery:{attempted:0,correct:0},general:{attempted:0,correct:0},
     marks:[],legacy:[],hiddenFromRoute:m.priority==='C',courseId:COURSE_ID,
     pdfDone:false,exerciseVideoDone:false,theoryStarted:false,completedBlocks:[],
     planningPriority:m.priority,
     plannedScope:m.scope,
     plannedAvailability:m.availability
   });
   codes.add(m.code);
 }
 ti.tcuCurriculumVersion='tcu-cebraspe-20261103-1';
 ti.tcuStudyStrategy={material:'Ramon Souza - TI Total',order:'preservar 36 unidades historicas; acrescentar ampliação A/B e reserva C',assessment:'prioridade Cebraspe, questões e revisões',releaseLimitations:'TI96 previsto 14/11/2026 e TI97 previsto 28/11/2026'};
 if(Array.isArray(current.goals)){
   const active=current.goals.find(g=>g.id==='meta-tcu-2');
   if(active&&Array.isArray(active.tasks)){
     active.tiTeacher='Ramon Souza — TI Total';
     for(const [id,unitId,title] of TASKS){
       const t=active.tasks.find(x=>x.id===id);
       if(t){t.title=title;t.unitId=unitId;}
     }
   }
   for(const goal of current.goals.filter(g=>g.number>2&&g.status==='locked')){
      goal.tiTeacher='Ramon Souza — TI Total';
      goal.tiPlanningGuide='Proxima unidade pendente da ementa TCU/Cebraspe; preservar bloqueio manual; nao liberar automaticamente.';
   }
 }
 current.tiCurriculumVersion='tcu-cebraspe-20261103-1';
 return current;
}
